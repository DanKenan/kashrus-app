import assert from 'node:assert/strict';
import { normalizeShifts, shiftUserIds, shiftPeopleOn, shiftsForUserOn, activeShiftsForUserAt, tasksVisibleOnShift, shiftPeopleSummary } from '../../src/lib/shifts.ts';
import { shiftAssigneeLabel } from '../../src/lib/shiftTaskDay.ts';
import { rewriteEmailRefs } from '../../src/server/account-merge.ts';
import { mount, recordFetch } from './lib/mini-render.mjs';
import { ShiftsPanel } from '../../src/components/ShiftsPanel.tsx';
