/** Item 9a unit tests: src/server/venue-scope.ts (fail closed, agency-bound, home default). */
import { enforceIdentityFields, mergeVenueAccess } from '../../src/server/identity.ts';
import { sanitizeVenueAccess, venueScope, resolveTargetVenue, sharedVenues, agencyVenueIds } from '../../src/server/venue-scope.ts';
let n = 0; const ok = (c, m) => { if (!c) throw new Error(m); n++; };
const V = [{ id: 'v1', agencyId: 'A' }, { id: 'v2', agencyId: 'A' }, { id: 'v3', agencyId: 'A' }, { id: 'vb', agencyId: 'B' }, { id: 'vh' }];
const J = JSON.stringify;
const run = async function () {
  const validA = agencyVenueIds(V, 'A');
  ok(J([...validA]) === J(['v1', 'v2', 'v3']), 'agency venue ids');
  ok(J([...agencyVenueIds(V, 'agency-hkc')]) === J(['vh']), 'legacy no-agency venue = agency-hkc');
  ok(J(sanitizeVenueAccess(['v2', 'v2', 'vb', 7, null, 'zz'], 'v1', validA)) === J(['v1', 'v2']), 'sanitize: dedupe, drop foreign/unknown/non-string, home first');
  ok(J(sanitizeVenueAccess('v2', 'v1', validA)) === J(['v1']), 'non-array list = home only');
  ok(J(sanitizeVenueAccess(['v2'], 'vb', validA)) === J(['v2']), 'foreign home not kept');
  const m = (o) => ({ role: 'mashgiach', agencyId: 'A', venueId: 'v1', personId: 'p', ...o });
  ok(J(venueScope(m({ venueAccess: ['v1', 'v2'] }), V)) === J(['v1', 'v2']), 'two venues');
  ok(J(venueScope(m({ venueAccess: [] }), V)) === J(['v1']), 'empty = home only');
  ok(J(venueScope(m({ venueAccess: 'all' }), V)) === J(['v1']), 'malformed = home only');
  ok(J(venueScope(m({ venueAccess: ['vb'] }), V)) === J(['v1']), 'foreign venue never authorizes');
  ok(J(venueScope(m({ venueId: 'gone', venueAccess: ['gone2', 'vb'] }), V)) === J(['gone']), 'removed home + junk: home id as before, never another venue');
  ok(J(venueScope(m({ venueId: undefined, venueAccess: ['vb', 'zz'] }), V)) === J([]), 'no home + foreign/unknown = none');
  ok(J(venueScope(m({ venueId: 'gone', venueAccess: ['v2'] }), V)) === J(['gone', 'v2']), 'removed home: only the explicit grant is added');
  ok(J(venueScope(m({ personId: undefined, venueAccess: ['v1', 'v2'] }), V)) === J(['v1']), 'unmigrated: home only');
  ok(venueScope({ role: 'admin', agencyId: 'A' }, V) === 'agency', 'admin agency');
  ok(J(venueScope(null, V)) === J([]) && J(venueScope({}, V)) === J([]), 'no user = none');
  // venue moved to another agency after the grant
  const Vmoved = V.map((v) => (v.id === 'v2' ? { ...v, agencyId: 'B' } : v));
  ok(J(venueScope(m({ venueAccess: ['v1', 'v2'] }), Vmoved)) === J(['v1']), 'current agency re-checked on every call');
  const u = m({ venueAccess: ['v1', 'v2'] });
  ok(J(resolveTargetVenue(u, V, 'v2')) === J({ ok: true, venueId: 'v2' }), 'explicit V2 allowed');
  ok(J(resolveTargetVenue(u, V, 'v3')) === J({ ok: false }), 'V3 forbidden');
  ok(J(resolveTargetVenue(u, V, 'vb')) === J({ ok: false }), 'foreign forbidden');
  ok(J(resolveTargetVenue(u, V, undefined)) === J({ ok: true, venueId: 'v1' }), 'default = home');
  ok(J(resolveTargetVenue(m({ venueId: undefined, venueAccess: ['v2'] }), V, undefined)) === J({ ok: true, venueId: null }), 'no home = null default, never another venue');
  ok(J(resolveTargetVenue({ role: 'admin', agencyId: 'A' }, V, 'vb')) === J({ ok: false }), 'admin cannot target another agency');
  ok(J(resolveTargetVenue({ role: 'admin', agencyId: 'A' }, V, 'v3')) === J({ ok: true, venueId: 'v3' }), 'admin any own venue');
  const c = m({ role: 'coordinator', venueAccess: ['v1', 'v2'] });
  ok(J(sharedVenues(c, m({ venueId: 'v2', venueAccess: ['v2', 'v3'] }), V)) === J(['v2']), 'shared v2');
  ok(J(sharedVenues(c, m({ venueId: 'v3', venueAccess: [] }), V)) === J([]), 'no shared venue');
  ok(J(sharedVenues(c, { ...m({ venueId: 'v1' }), agencyId: 'B' }, V)) === J([]), 'cross-agency never shared');
  // identity invariant (must-fix 1): grants survive unrelated commits
  const ag = [{ id: 'A', adminEmail: 'a@x' }];
  const base = [{ id: 'u1', personId: 'u1', role: 'mashgiach', agencyId: 'A', venueId: 'v1', venueAccess: ['v1'] }];
  const viol = []; const opt = (o = {}) => ({ onViolation: (r, f) => viol.push(`${r}:${f}`), ...o });
  let g = enforceIdentityFields(base, base.map((u) => ({ ...u })), ag, opt({ venueAccessSetById: new Map([['u1', ['v2', 'v2', 7]]]) }));
  ok(J(g[0].venueAccess) === J(['v1', 'v2']), 'sanctioned grant: home first, deduped, strings only');
  let g2 = enforceIdentityFields(g, g.map((u) => ({ ...u, name: 'renamed' })), ag, opt());
  ok(J(g2[0].venueAccess) === J(['v1', 'v2']), 'unrelated commit keeps the grant');
  let g3 = enforceIdentityFields(g2, g2.map((u) => ({ ...u, venueAccess: ['v1', 'v2', 'v3'] })), ag, opt());
  ok(J(g3[0].venueAccess) === J(['v1', 'v2']) && viol.includes('u1:venueAccess'), 'raw venueAccess from a mutator reverted and reported');
  let g4 = enforceIdentityFields(g2, g2.map((u) => { const { venueAccess, ...r } = u; return r; }), ag, opt());
  ok(J(g4[0].venueAccess) === J(['v1', 'v2']), 'dropping the field keeps the stored list');
  let g5 = enforceIdentityFields(g2, g2.map((u) => ({ ...u, venueId: 'v3' })), ag, opt());
  ok(J(g5[0].venueAccess) === J(['v3']), 'home change without a sanctioned list resets to the new home (never expands)');
  let g6 = enforceIdentityFields(g2, g2.map((u) => ({ ...u, venueId: 'v3' })), ag, opt({ venueAccessSetById: new Map([['u1', ['v1', 'v2']]]) }));
  ok(J(g6[0].venueAccess) === J(['v3', 'v1', 'v2']), 'home change + list in one commit stay consistent');
  let g7 = enforceIdentityFields([], [{ id: 'n1', role: 'mashgiach', agencyId: 'A', venueId: 'v2', venueAccess: ['v1', 'v2', 'v3'] }], ag, opt());
  ok(J(g7[0].venueAccess) === J(['v2']), 'a new row starts at [venueId], whatever the body said');
  let g8 = enforceIdentityFields([{ id: 'l1', role: 'mashgiach', venueId: 'v1' }], [{ id: 'l1', role: 'mashgiach', venueId: 'v1', venueAccess: ['v2'] }], ag, opt());
  ok(g8[0].venueAccess === undefined, 'unmigrated row carries no venueAccess');
  ok(J(mergeVenueAccess(undefined, ['v2', '', null, 'v2'])) === J(['v2']), 'merge without home');
  console.log(`venue-scope: ${n}/${n} passed`);
};
export default { name: 'venue-scope (9a)', whatItProves: 'Multi-venue scope fails closed: home venue as before; extra venues only server-granted, current-agency; defaults to home; admins never cross agencies; coordinators share only real venues.', run };
