import assert from 'node:assert/strict';
import { mount, recordFetch } from './lib/mini-render.mjs';
import { TaskModal } from '../../src/components/TaskModal.tsx';
import { TaskFormProgress } from '../../src/components/TaskFormProgress.tsx';

recordFetch({});
const view = mount(TaskModal, { isOpen: true, onClose() {}, onSave() {}, venueId: 'v', venueName: 'Kitchen', knownWorkers: [] });
await view.render();
assert.match(view.html(), /aria-label="Task steps"/);
assert.match(view.html(), /aria-current="step" data-step-name="What"/);
assert.match(view.html(), /Kitchen/);
await view.type('task-title-input', 'Check eggs');
await view.click('Add another task');
assert.match(view.html(), /data-task-count="true"/);
assert.match(view.html(), /2 tasks/);
const secondName = view.find((e) => e.props['aria-label'] === 'Task 2 name')[0];
await secondName.props.onChange({ target: { value: 'Check sink' } });
await view.render();
await view.submit();
assert.match(view.html(), /aria-label="Edit What"/);
assert.match(view.html(), /2 tasks · Check eggs, Check sink/);
assert.match(view.html(), /aria-current="step" data-step-name="When"/);
let edited;
const progress = mount(TaskFormProgress, { step: 2, count: 2, summaries: ['2 tasks · Check eggs, Check sink', 'Afternoon · every day'], onEdit: (step) => { edited = step; } });
await progress.render();
await progress.click('Edit What');
assert.equal(edited, 0);
await progress.click('Edit When');
assert.equal(edited, 1);
console.log('task form look: stepper, task count, and editable summaries passed');
