import assert from 'node:assert/strict';
import { shiftPersonOn, shiftRunsOn, shiftsForUserOn, formatShiftHours, shiftLabel, minutesInShift, taskWithShiftTimes, tasksVisibleOnShift } from '../../src/lib/shifts.ts';
const day = '2026-11-01'; // Sunday
const user = { id: 'u1', email: 'one@example.test' };
const shift = { id: 's1', agencyId: 'a', venueId: 'v', name: 'Deli day', area: 'Deli', daysOfWeek: [0], startMinutes: 480, endMinutes: 1080, userId: 'u1', overrides: [], createdAt: day };
const other = { ...shift, id: 's2', userId: 'u2' };
assert.equal(shiftPersonOn(shift, day), 'u1');
const replaced = { ...shift, overrides: [{ date: day, userId: 'u2' }] };
assert.equal(shiftPersonOn(replaced, day), 'u2');
assert.equal(shiftPersonOn(replaced, '2026-11-08'), 'u1');
assert.equal(shiftPersonOn({ ...replaced, overrides: [{ date: day, userId: null }] }, day), null);
assert.equal(shiftRunsOn(shift, day, 0), true);
assert.equal(shiftRunsOn(shift, '2026-11-02', 1), false);
assert.deepEqual(shiftsForUserOn([shift, other], 'u1', day, 0), [shift]);
assert.deepEqual(shiftsForUserOn([replaced], 'u1', day, 0), []);
assert.deepEqual(shiftsForUserOn([replaced], 'u2', day, 0), [replaced]);
assert.equal(formatShiftHours(shift), '8:00 AM – 6:00 PM');
assert.equal(shiftLabel(shift), 'Deli day · 8:00 AM – 6:00 PM');
const night = { ...shift, name: 'Night', startMinutes: 1320, endMinutes: 120 };
for (const m of [1320, 1410, 60, 120]) assert.equal(minutesInShift(night, m), true);
for (const m of [900, 1319, 121, -1, 1440, NaN]) assert.equal(minutesInShift(night, m), false);
assert.equal(shiftRunsOn(night, day, 0), true);
assert.equal(shiftRunsOn(night, '2026-11-02', 1), false);
assert.equal(formatShiftHours({ ...shift, startMinutes: 0, endMinutes: 720 }), '12:00 AM – 12:00 PM');
const task = (id, extra = {}) => ({ id, venueId: 'v', assignedTo: ['all'], ...extra });
const ts = [task('own', { shiftId: 's1' }), task('other', { shiftId: 's2' }), task('inside', { targetTime: '9:00 AM' }), task('window', { targetTime: '10:00 AM', targetTime2: '11:00 PM' }), task('outside', { targetTime: '7:00 PM', targetTimeMinutes: 1140 }), task('none'), task('any', { targetTime: 'Any time' }), task('eod', { targetTime: 'End of Day' }), task('personal', { assignedTo: ['ONE@example.test'], shiftId: 's2', targetTime: '11:00 PM' }), task('someone', { assignedTo: ['two@example.test'] }), task('unknown', { shiftId: 'deleted', targetTime: '9:00 AM' }), task('unknown-outside', { shiftId: 'deleted', targetTime: '11:00 PM' })];
const visible = (shifts, viewer = user, tasks = ts, weekday = 0) => tasksVisibleOnShift(tasks, shifts, viewer, day, weekday).map((t) => t.id);
assert.deepEqual(visible([shift, other]), ['own', 'inside', 'window', 'none', 'any', 'eod', 'personal', 'unknown']);
const fallback = ts.filter((t) => t.id !== 'someone').map((t) => t.id);
assert.deepEqual(visible([]), fallback);
assert.deepEqual(visible([shift, other], { ...user, id: 'off' }), fallback);
assert.deepEqual(visible([shift, other], user, ts, 1), fallback);
assert.deepEqual(visible([{ ...shift, overrides: [{ date: day, userId: null }] }]), fallback);
assert.deepEqual(visible([night], user, [task('late', { targetTime: '11:30 PM' }), task('early', { targetTime: '1:00 AM' }), task('afternoon', { targetTime: '3:00 PM' })]), ['late', 'early']);
const raw = task('projection', { shiftId: 's1', daysOfWeek: [2], targetTime: 'Any time' });
const effective = taskWithShiftTimes(raw, new Map([[shift.id, shift]]));
assert.deepEqual(effective.daysOfWeek, [0]);
assert.equal(effective.targetTime, '8:00 AM');
assert.equal(effective.targetTime2, '6:00 PM');
assert.equal(effective.targetTimeMinutes, 480);
assert.equal(effective.targetTime2Minutes, 1080);
assert.deepEqual(raw.daysOfWeek, [2]);
assert.equal(taskWithShiftTimes(raw, {}), raw);
assert.equal(taskWithShiftTimes({ ...raw, venueId: 'elsewhere' }, { s1: shift }).targetTime, 'Any time');
assert.equal(taskWithShiftTimes(raw, { s1: shift }).targetTimeMinutes, 480);
const unbound = task('normal');
assert.equal(taskWithShiftTimes(unbound, { s1: shift }), unbound);
assert.equal(taskWithShiftTimes(raw, { s1: { ...shift, daysOfWeek: [5], startMinutes: 600 } }).targetTimeMinutes, 600);
console.log('PASS shifts: person, overrides, start-day semantics, hours, visibility, fallback, and live task projection');
