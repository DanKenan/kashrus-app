import assert from 'node:assert/strict';
import React from 'react';
import { ChevronDown } from 'lucide-react';
import { readFileSync } from 'node:fs';
import { mount } from './lib/mini-render.mjs';
import { MashgiachBoard } from '../../src/components/MashgiachBoard.tsx';
const task = { id: 't', title: 'Walk-in fridge temperature check', inputType: 'checkbox', category: 'General', assignedTo: ['all'], daysOfWeek: [], isCompleted: true, updatedByName: 'Yossi Cohen', updatedAt: '2026-11-08T16:12:00Z' };
const props = { tasks: [task], currentUser: { id: 'u', role: 'mashgiach' }, timeZone: 'UTC', onUpdateStatus() {}, onCheckIn() {}, onUpdateNotes() {}, onEditTask() {}, onDeleteTask() {} };
const view = mount(MashgiachBoard, props); await view.render();
function* walk(node) { if (Array.isArray(node)) { for (const n of node) yield* walk(n); } else if (React.isValidElement(node)) { yield node; yield* walk(node.props.children); } }
const chevron = () => [...walk(view.tree())].find((e) => e.type === ChevronDown);
const summary = () => view.find((e) => e.props['aria-controls'] === 'mboard-done')[0];
assert.equal(summary().props['aria-expanded'], false);
assert.equal(chevron().props.className.includes('rotate-180'), false);
assert.match(summary().props.className, /mboard-row/);
const allDone = view.find((e) => e.type === 'section' && e.props.className?.includes('bg-ok-bg'))[0];
assert.match(allDone.props.className, /text-ok/);
await view.click('Done today');
assert.equal(summary().props['aria-expanded'], true);
assert.equal(chevron().props.className.includes('rotate-180'), true);
assert.match(view.text(), /Yossi · 4:12 PM/);
const attribution = view.find((e) => e.type === 'span' && e.props.className === 'shrink-0 text-xs tnum')[0];
assert.ok(attribution);
await view.click('Done today'); assert.equal(summary().props['aria-expanded'], false);
await view.render({ tasks: [{ ...task, id: 'next', isCompleted: false, targetTime: '4:00 PM' }, { ...task, id: 'later', isCompleted: false, targetTime: '04:30 PM', targetTime2: '05:30 PM' }] });
const title = view.find((e) => e.type === 'span' && e.props.children === task.title && e.props.className?.includes('break-words'))[0];
assert.ok(title); assert.doesNotMatch(title.props.className, /truncate/);
const css = readFileSync(new URL('../../src/components/MashgiachBoard.css', import.meta.url), 'utf8');
assert.match(css, /\.mboard-segment-done \{ background: var\(--ok\); \}/);
assert.doesNotMatch(css, /\.mboard-segment-done[^}]*ok-bg|\.mboard-segment-done[^}]*border/);
assert.match(css, /min-height: 48px/);
console.log('mboard round 3: solid progress, green completion card, fold chevron, attribution and wrapping passed');
