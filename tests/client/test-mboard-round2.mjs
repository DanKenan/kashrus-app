import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { mount } from './lib/mini-render.mjs';
import { mashgiachProgress, mashgiachCheckInCovered, mashgiachCheckInSummary } from '../../src/lib/mashgiachBoard.ts';
import { checkInCoversDue } from '../../src/lib/overdue.ts';
import { shiftTaskOverdueAt } from '../../src/lib/shifts.ts';
import { MashgiachBoard } from '../../src/components/MashgiachBoard.tsx';
import { TaskCardView } from '../../src/components/TaskCardView.tsx';
const task = { id: 'check', title: 'Repeat check', category: 'General', inputType: 'check_in', targetTime: '8:00 AM', targetTime2: '4:00 PM', assignedTo: ['all'], daysOfWeek: [], isCompleted: false, currentStatus: 'pending', notes: '', checkIns: [{ id: 'c', at: '2026-11-08T07:00:00Z', byName: 'Yossi Cohen' }] };
const day = '2026-11-08';
const covered = (t, minutes = 600) => mashgiachCheckInCovered(t, undefined, day, 0, minutes, 'UTC');
assert.equal(covered(task), checkInCoversDue(task, day, 600, 'UTC'));
assert.equal(covered(task), true);
assert.equal(covered(task, 1020), false); // The next passed deadline uses the existing coverage window.
assert.equal(covered({ ...task, checkIns: [] }), false);
assert.equal(covered({ ...task, checkIns: [{ at: '2026-11-07T07:00:00Z' }] }), false);
const nextTask = { ...task, id: 'next', inputType: 'checkbox', checkIns: [], targetTime: '9:00 AM' };
const board = mashgiachProgress([task, nextTask], () => false, covered);
assert.equal(board.next.id, 'next');
assert.deepEqual(board.later.map((t) => t.id), ['check']);
assert.equal(board.completed, 0);
assert.equal(board.total, 2);
assert.equal(mashgiachProgress([task], () => false, covered).next, undefined);
assert.equal(mashgiachProgress([task], () => false, (t) => covered(t, 1020)).next.id, 'check');
const shift = { id: 's', name: 'Evening', startMinutes: 960, endMinutes: 1380, days: Array.from({ length: 7 }, () => ({ on: true })), userIds: ['u'], overrides: [] };
const shifted = { ...task, shiftId: 's', checkIns: [{ at: '2026-11-08T17:00:00Z' }] };
assert.equal(mashgiachCheckInCovered(shifted, shift, day, 0, 1400, 'UTC'), true);
assert.equal(shiftTaskOverdueAt(shift, day, 0, 1400, shifted, 'UTC'), false);
assert.equal(mashgiachCheckInCovered(task, shift, day, 0, 1400, 'UTC'), false);
assert.equal(shiftTaskOverdueAt(shift, day, 0, 1400, task, 'UTC'), true);
const night = { ...shift, startMinutes: 1320, endMinutes: 360 };
const overnight = { ...task, checkIns: [{ at: '2026-11-07T23:00:00Z' }] };
assert.equal(mashgiachCheckInCovered(overnight, night, day, 0, 120, 'UTC'), true);
assert.equal(mashgiachCheckInCovered(overnight, night, day, 0, 500, 'UTC'), true);
assert.equal(shiftTaskOverdueAt(night, day, 0, 500, overnight, 'UTC'), false);
assert.equal(mashgiachCheckInCovered(overnight, night, day, 0, 1380, 'UTC'), false);
const ownTime = { ...task, shiftTime: true, targetTime: '10:30 PM', targetTime2: '3:00 AM', checkIns: [{ at: '2026-11-07T22:15:00Z' }] };
assert.equal(mashgiachCheckInCovered(ownTime, night, day, 0, 120, 'UTC'), true);
assert.equal(mashgiachCheckInCovered(ownTime, night, day, 0, 240, 'UTC'), false);
assert.equal(shiftTaskOverdueAt(night, day, 0, 240, ownTime, 'UTC'), true);
assert.equal(mashgiachCheckInSummary(task, new Date('2026-11-08T10:00:00Z'), 'UTC'), '1 check today · last 7:00 AM');
const props = { tasks: [{ ...task, targetTime: '', targetTime2: '', checkIns: [{ id: 'now', at: new Date().toISOString(), byName: 'Yossi Cohen' }] }], currentUser: { id: 'u', role: 'mashgiach', email: 'u@test' }, timeZone: 'UTC', onUpdateStatus() {}, onCheckIn() {}, onUpdateNotes() {}, onEditTask() {}, onDeleteTask() {} };
const view = mount(MashgiachBoard, props); await view.render();
assert.match(view.text(), /All done for now/); assert.doesNotMatch(view.text(), /All done for today|Do this next/);
assert.match(view.text(), /0 of 1 done/); assert.match(view.text(), /1 check today · last/);
assert.match(view.text(), /Later in your shift/);
await view.click('Repeat check'); assert.equal(view.find((e) => e.props['aria-expanded'] === true).length, 1);
const done = { ...nextTask, isCompleted: true, updatedByName: 'Yossi Cohen', updatedAt: '2026-11-08T16:12:00Z' };
await view.render({ tasks: [done] }); assert.match(view.text(), /All done for today/);
assert.match(view.text(), /Yossi · 4:12 PM/); assert.doesNotMatch(view.text(), /Yossi Cohen/);
const RealDate = globalThis.Date;
globalThis.Date = class extends RealDate { constructor(...args) { super(...(args.length ? args : ['2026-11-08T18:00:00Z'])); } };
try {
  await view.render({ tasks: [{ ...nextTask, id: 'first', targetTime: '12:01 AM' }, { ...nextTask, id: 'late', title: 'Late task', targetTime: '12:02 AM' }] });
  assert.match(view.text(), /Late task Late/);
} finally { globalThis.Date = RealDate; }
const normal = mount(TaskCardView, props); await normal.render(); assert.match(normal.text(), /1 check logged/);
const focus = mount(TaskCardView, { ...props, focused: true }); await focus.render();
assert.doesNotMatch(focus.text(), /check logged|last by/); assert.match(focus.text(), /YC/);
const css = readFileSync(new URL('../../src/components/MashgiachBoard.css', import.meta.url), 'utf8');
assert.doesNotMatch(css, /@font-face|https?:|\[class\*=bg-gold\]/);
assert.match(css, /font-family: var\(--font-sans\)/);
assert.match(css, /\.mboard-header \{ background: var\(--ink\); color: var\(--paper\)/);
console.log('mboard round 2: coverage, later rows, unchanged progress, now/today, attribution, avatars and local font passed');
