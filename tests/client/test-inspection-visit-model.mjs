import assert from 'node:assert/strict';
import { buildPayload, newDraft, restoreDraft, saveDraft, setMark, visitCounts, visitScope, queueReport, readOutbox, retryResult, retryDue, storeOutbox, acceptReport, draftKey } from '../../src/lib/inspectionVisit.ts';
const data = new Map();
const storage = { get length() { return data.size; }, key: i => [...data.keys()][i] ?? null, getItem: k => data.get(k) ?? null, setItem: (k, v) => data.set(k, v), removeItem: k => data.delete(k) };
const list = { company: { id: 'factory-1', name: ' Factory  שם ', brand: '', plant: '' }, listVersion: 'hash-1', ingredients: [{ id: 'i1' }, { id: 'i2' }], products: [{ id: 'p1' }] };
const scope = visitScope('user-1', 'agency-1');
const initial = newDraft(list, '12345678-1234', '2026-11-10T12:00:00.000Z');
let draft = setMark(initial, 'ingredient', 'i1', { status: 'checked' });
draft = setMark(draft, 'ingredient', 'i2', { status: 'not_used' });
draft = setMark(draft, 'product', 'p1', { status: 'alert', note: ' Label  אחר ' });
draft.note = ' Report  text\nunchanged ';
draft.offList = [{ name: ' New  שם ', brand: ' Brand ', note: ' Note ' }];
draft.editor = { index: 0, initial: { name: 'Unfinished' } };
saveDraft(storage, scope, draft);
assert.deepEqual(restoreDraft(storage, scope, list), { draft, listChanged: false });
assert.equal(restoreDraft(storage, visitScope('user-2', 'agency-1'), list), null);
assert.equal(restoreDraft(storage, visitScope('user-1', 'agency-2'), list), null);
const changed = restoreDraft(storage, scope, { ...list, listVersion: 'hash-2', ingredients: [{ id: 'i1' }] });
assert.equal(changed.listChanged, true);
assert.equal(changed.draft.listVersion, 'hash-1');
assert.deepEqual(changed.draft.marks.map(m => m.itemId), ['i1', 'p1']);
assert.equal(changed.draft.clientReportId, draft.clientReportId);
assert.deepEqual(visitCounts(draft), { checked: 1, not_used: 1, alert: 1, offList: 1 });
assert.equal(setMark(draft, 'ingredient', 'i1', null).marks.length, 2);
assert.equal(setMark(draft, 'ingredient', 'i1', { status: 'alert', note: 'Note' }).marks.length, 3);
const payload = buildPayload(draft);
assert.equal(payload.editor, undefined);
assert.equal(payload.note, draft.note);
assert.deepEqual(payload.offList, draft.offList);
assert.deepEqual(payload.marks.map(m => m.status), ['checked', 'not_used', 'alert']);
assert.equal(buildPayload(initial).marks.length, 0);
assert.throws(() => buildPayload({ ...draft, marks: [{ kind: 'ingredient', itemId: 'i1', status: 'alert' }] }), /needs a note or photo/);
assert.throws(() => buildPayload({ ...draft, marks: [{ kind: 'ingredient', itemId: 'i1', status: 'other' }] }), /Invalid item/);
assert.throws(() => buildPayload({ ...draft, marks: [draft.marks[0], draft.marks[0]] }), /only one mark/);
const photo = 'data:image/jpeg;base64,YQ==';
assert.equal(buildPayload({ ...initial, marks: [{ kind: 'ingredient', itemId: 'i1', status: 'alert', photo }] }).marks[0].photo, photo);
const four = { ...initial, offList: Array.from({ length: 4 }, (_, i) => ({ name: `Item ${i}`, photo })) };
assert.equal(buildPayload(four).offList.length, 4);
assert.throws(() => buildPayload({ ...four, offList: [...four.offList, { name: 'Fifth', photo }] }), /up to 4 photos/);
assert.throws(() => buildPayload(four, 10), /smaller/);
assert.throws(() => buildPayload({ ...initial, offList: [{ name: ' ', photo: 'data:image/svg+xml;base64,YQ==' }] }), /item name/);
assert.throws(() => buildPayload({ ...initial, offList: [{ name: 'Item', photo: 'data:image/svg+xml;base64,YQ==' }] }), /smaller/);
assert.throws(() => buildPayload({ ...initial, note: 'x'.repeat(4001) }), /limit/);
assert.throws(() => buildPayload({ ...initial, offList: [{ name: 'Item', note: 'x'.repeat(1001) }] }), /1000/);
assert.throws(() => buildPayload({ ...initial, offList: Array.from({ length: 51 }, () => ({ name: 'Item' })) }), /limit/);
assert.throws(() => buildPayload({ ...initial, marks: Array.from({ length: 2001 }, (_, i) => ({ kind: 'product', itemId: `${i}`, status: 'checked' })) }), /limit/);
const entry = queueReport(storage, scope, draft);
assert.deepEqual(readOutbox(storage, scope), [entry]);
for (const status of [0, 500, 503]) {
  const retry = retryResult(entry, status, 'Offline', 1000);
  assert.equal(retry.stopped, false);
  assert.equal(retry.draft.clientReportId, draft.clientReportId);
  assert.equal(retryDue(retry, 1000), false);
  assert.equal(retryDue(retry, retry.nextAttempt), true);
  assert.ok(retryResult(retry, status, 'Offline', 1000).nextAttempt > retry.nextAttempt);
}
for (const status of [400, 401, 403, 404, 409, 429]) {
  const stopped = retryResult(entry, status, 'Server error text', 1000);
  assert.equal(stopped.stopped, true);
  assert.equal(stopped.error, 'Server error text');
  assert.equal(retryDue(stopped, Infinity), false);
}
storeOutbox(storage, scope, retryResult(entry, 503, 'Retry', 1000));
assert.equal(readOutbox(storage, scope)[0].attempts, 1);
const sent = { report: { id: 'report-1' }, fee: null };
acceptReport(storage, scope, entry, sent);
assert.equal(storage.getItem(draftKey(scope, draft.companyId)), null);
assert.deepEqual(readOutbox(storage, scope)[0].sent, sent);
assert.equal(retryDue(readOutbox(storage, scope)[0], Infinity), false);
// An acknowledgement for an earlier report cannot clear a newer draft.
saveDraft(storage, scope, { ...draft, clientReportId: 'new-report-123' });
acceptReport(storage, scope, entry, sent);
assert.equal(JSON.parse(storage.getItem(draftKey(scope, draft.companyId))).clientReportId, 'new-report-123');
console.log('inspection visit model: passed');
