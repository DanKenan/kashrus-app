const sunday = '2026-11-08', monday = '2026-11-09';
const shift = { id: 's', agencyId: 'a', venueId: 'v', name: 'Deli day', area: '', days: Array.from({ length: 7 }, () => ({ on: true })), startMinutes: 480, endMinutes: 1080, userIds: ['m', 'y'], userNames: ['Moshe Levin', 'Yossi Katz'], userId: 'm', userName: 'Moshe Levin', overrides: [], createdAt: '' };
const other = { ...shift, id: 'other', userIds: ['d'], userId: 'd' };
const task = { id: 'task', title: 'Temperature log', shiftId: 's', shiftTime: true, targetTime: '2:00 PM', targetTimeMinutes: 840, venueId: 'v', assignedTo: ['all'], createdAt: '' };
for (const id of ['m', 'y']) {
  assert.deepEqual(shiftsForUserOn([shift], id, sunday, 0), [shift]);
  for (const minutes of [420, 900, 1200]) assert.deepEqual(tasksVisibleOnShift([task], [shift, other], { id, email: `${id}@test.local` }, sunday, 0, minutes), [task]);
}
assert.deepEqual(tasksVisibleOnShift([task], [shift, other], { id: 'd', email: 'd@test.local' }, sunday, 0, 900), []);
const weekly = { ...shift, days: shift.days.map((d, w) => w === 1 ? { ...d, userIds: ['y', 'd'], userId: 'y', userNames: ['Yossi Katz', 'Dovid Rosen'] } : d) };
assert.deepEqual(shiftPeopleOn(weekly, monday), ['y', 'd']);
const changed = { ...weekly, overrides: [{ date: monday, userIds: ['m', 'c'], userId: 'm', userNames: ['Moshe Levin', 'Cora Lev'] }] };
assert.deepEqual(shiftPeopleOn(changed, monday), ['m', 'c']);
assert.deepEqual(shiftPeopleOn({ ...changed, overrides: [{ date: monday, userIds: [], userId: 'm' }] }, monday), []);
assert.deepEqual(shiftPeopleOn({ ...weekly, days: weekly.days.map((d, w) => w === 1 ? { on: true, userIds: null } : d) }, monday), []);
const legacy = { ...shift, userIds: undefined, days: shift.days.map((d, w) => w === 1 ? { ...d, userId: 'y' } : d), overrides: [{ date: sunday, userId: 'd' }] };
const normalized = normalizeShifts([legacy])[0];
assert.deepEqual(normalized.userIds, ['m']);
assert.deepEqual(normalized.days[1].userIds, ['y']);
assert.deepEqual(normalized.overrides[0].userIds, ['d']);
assert.deepEqual(shiftPeopleOn(legacy, sunday), ['d']);
assert.deepEqual(shiftPeopleOn(legacy, monday), ['y']);
assert.deepEqual(shiftUserIds({ userId: null }), []);
assert.deepEqual(shiftUserIds({ userIds: [], userId: 'm' }), []);
assert.deepEqual(normalizeShifts([{ ...shift, userIds: ['m', 'm', 'y'] }])[0].userIds, ['m', 'y']);
const night = { ...shift, days: shift.days.map((d, w) => ({ on: w === 0 })), startMinutes: 1320, endMinutes: 120 };
for (const id of ['m', 'y']) assert.deepEqual(activeShiftsForUserAt([night], id, monday, 1, 60), [night]);
assert.equal(shiftPeopleSummary(shift.userNames), 'Moshe Levin + 1');
assert.equal(shiftAssigneeLabel(shift, true, sunday, 0, 900), 'Deli day · today: Moshe Levin, Yossi Katz');
assert.equal(shiftAssigneeLabel(changed, true, monday, 1, 900), 'Deli day · today: Moshe Levin, Cora Lev');
const remapped = rewriteEmailRefs({ shifts: [{ ...changed, userIds: ['m', 'y'], days: [{ on: true, userIds: ['m', 'y'] }], overrides: [{ date: sunday, userIds: ['m', 'y'] }] }] }, new Set(['a']), 'm@test.local', 'y@test.local', new Map([['m', 'y']]));
assert.equal(remapped.ok, true);
for (const row of [remapped.patch.shifts[0], remapped.patch.shifts[0].days[0], remapped.patch.shifts[0].overrides[0]]) assert.deepEqual(row.userIds, ['y']);
assert.equal(rewriteEmailRefs({ shifts: [{ venueId: 'unknown', userIds: ['m'] }] }, new Set(['a']), 'm@test.local', 'y@test.local', new Map([['m', 'y']])).ok, false);

const storage = new Map();
globalThis.localStorage = { getItem: (k) => storage.get(k) ?? null, setItem: (k, v) => storage.set(k, v), removeItem: (k) => storage.delete(k) };
const people = [{ id: 'm', name: 'Moshe Levin' }, { id: 'y', name: 'Yossi Katz' }, { id: 'd', name: 'Dovid Rosen' }];
